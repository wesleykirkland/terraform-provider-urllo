"""Unit tests for check_docs.py.

Run via `make test-py`, or directly with:
    python3 -m unittest scripts.test_check_docs -v
Each test builds a small synthetic repo tree under a TemporaryDirectory
rather than touching the real repository, so these stay fast and don't
depend on (or corrupt) this repo's actual README/docs state.
"""

from __future__ import annotations

import sys
import tempfile
import unittest
from contextlib import contextmanager
from pathlib import Path
from typing import Iterator
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parent))

import check_docs  # noqa: E402


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


RESOURCE_GO = """\
package provider

func (r *ExampleResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
\tresp.TypeName = req.ProviderTypeName + "_%s"
}
"""

DOC_HEADER = """\
---
# generated by https://github.com/hashicorp/terraform-plugin-docs
page_title: "urllo_%s"
---

# doc body
"""


class TempRepo:
    """A minimal synthetic repo tree that satisfies check_docs's assumptions."""

    def __init__(self, root: Path) -> None:
        self.root = root

    def add_resource(self, suffix: str, *, with_type_name: bool = True) -> None:
        content = RESOURCE_GO % suffix if with_type_name else "package provider\n"
        write(self.root / "internal" / "provider" / f"{suffix}_resource.go", content)

    def add_data_source(self, suffix: str) -> None:
        write(self.root / "internal" / "provider" / f"{suffix}_data_source.go", RESOURCE_GO % suffix)

    def add_resource_doc(self, suffix: str) -> None:
        write(self.root / "docs" / "resources" / f"{suffix}.md", DOC_HEADER % suffix)

    def add_data_source_doc(self, suffix: str) -> None:
        write(self.root / "docs" / "data-sources" / f"{suffix}.md", DOC_HEADER % suffix)

    def set_readme(self, content: str) -> None:
        write(self.root / "README.md", content)

    def set_provider_go(self, content: str) -> None:
        write(self.root / "internal" / "provider" / "provider.go", content)

    def set_tf_readme(self, content: str) -> None:
        write(self.root / "terraform" / "README.md", content)

    def add_tf_file(self, name: str) -> None:
        write(self.root / "terraform" / name, "# tf file\n")


@contextmanager
def temp_repo() -> Iterator[TempRepo]:
    with tempfile.TemporaryDirectory() as tmp:
        yield TempRepo(Path(tmp))


class CheckResourcesAndDataSourcesTest(unittest.TestCase):
    def test_fully_documented_resource_passes(self) -> None:
        with temp_repo() as repo:
            repo.add_resource("rule")
            repo.add_resource_doc("rule")
            readme = "See [urllo_rule](docs/resources/rule.md) for details."
            failures = check_docs.check_resources_and_data_sources(repo.root, readme)
            self.assertEqual(failures, [])

    def test_missing_generated_doc_is_reported(self) -> None:
        with temp_repo() as repo:
            repo.add_resource("rule")
            readme = "See [urllo_rule](docs/resources/rule.md) for details."
            failures = check_docs.check_resources_and_data_sources(repo.root, readme)
            self.assertEqual(len(failures), 1)
            self.assertIn("docs/resources/rule.md", failures[0])
            self.assertIn("no generated doc", failures[0])

    def test_missing_readme_link_is_reported(self) -> None:
        with temp_repo() as repo:
            repo.add_resource("rule")
            repo.add_resource_doc("rule")
            failures = check_docs.check_resources_and_data_sources(repo.root, "README with no link")
            self.assertEqual(len(failures), 1)
            self.assertIn("does not link", failures[0])

    def test_missing_type_name_line_is_reported(self) -> None:
        with temp_repo() as repo:
            repo.add_resource("rule", with_type_name=False)
            failures = check_docs.check_resources_and_data_sources(repo.root, "")
            self.assertEqual(len(failures), 1)
            self.assertIn("can't determine its type name", failures[0])

    def test_data_source_uses_data_sources_directory(self) -> None:
        with temp_repo() as repo:
            repo.add_data_source("hosts")
            repo.add_data_source_doc("hosts")
            readme = "[urllo_hosts](docs/data-sources/hosts.md)"
            failures = check_docs.check_resources_and_data_sources(repo.root, readme)
            self.assertEqual(failures, [])
            # Sanity: the doc must be expected under data-sources/, not resources/.
            self.assertFalse((repo.root / "docs" / "resources" / "hosts.md").exists())


