class CheckMarkdownFormatTest(unittest.TestCase):
    def test_missing_referenced_file_is_skipped_not_errored(self) -> None:
        with temp_repo() as repo:
            repo.set_readme("# Title\n\nok\n")
            # terraform/README.md deliberately left absent.
            failures = check_docs.check_markdown_format(repo.root)
            self.assertEqual(failures, [])

    def test_well_formed_file_passes(self) -> None:
        with temp_repo() as repo:
            repo.set_readme(
                "# Title\n\n"
                "| A | B |\n"
                "| - | - |\n"
                "| 1 | 2 |\n\n"
                "[link](terraform/README.md)\n"
            )
            repo.set_tf_readme("ok\n")
            failures = check_docs.check_markdown_format(repo.root)
            self.assertEqual(failures, [])

    def test_unbalanced_fence_is_reported(self) -> None:
        with temp_repo() as repo:
            repo.set_readme("# Title\n\n```hcl\nfoo = 1\n")
            repo.set_tf_readme("ok\n")
            failures = check_docs.check_markdown_format(repo.root)
            self.assertTrue(any("unbalanced" in f for f in failures))

    def test_ragged_table_is_reported(self) -> None:
        with temp_repo() as repo:
            repo.set_readme("# Title\n\n| A | B |\n| - | - |\n| 1 | 2 | 3 |\n")
            repo.set_tf_readme("ok\n")
            failures = check_docs.check_markdown_format(repo.root)
            self.assertTrue(any("table row has" in f for f in failures))

    def test_broken_relative_link_is_reported(self) -> None:
        with temp_repo() as repo:
            repo.set_readme("# Title\n\n[nowhere](docs/does-not-exist.md)\n")
            repo.set_tf_readme("ok\n")
            failures = check_docs.check_markdown_format(repo.root)
            self.assertTrue(any("does not resolve" in f for f in failures))

    def test_pipes_inside_fenced_code_are_ignored(self) -> None:
        with temp_repo() as repo:
            repo.set_readme("# Title\n\n```hcl\n| this looks like a table row |\n```\n")
            repo.set_tf_readme("ok\n")
            failures = check_docs.check_markdown_format(repo.root)
            self.assertEqual(failures, [])

    def test_external_and_anchor_links_are_ignored(self) -> None:
        with temp_repo() as repo:
            repo.set_readme("# Title\n\n[ext](https://example.com/x)\n\n[anchor](#title)\n")
            repo.set_tf_readme("ok\n")
            failures = check_docs.check_markdown_format(repo.root)
            self.assertEqual(failures, [])


