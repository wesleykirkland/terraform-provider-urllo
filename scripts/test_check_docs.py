def build_fully_valid_repo(repo: TempRepo) -> None:
    repo.add_resource("rule")
    repo.add_resource_doc("rule")
    repo.set_provider_go('"api_key": schema.StringAttribute{\n')
    repo.add_tf_file("provider.tf")
    repo.set_tf_readme("Uses `provider.tf`.\n")
    repo.set_readme(
        "# Title\n\nthe `api_key` setting\n\n[urllo_rule](docs/resources/rule.md)\n"
    )


class RunAllChecksAndMainTest(unittest.TestCase):
    def test_run_all_checks_on_valid_repo_returns_no_failures(self) -> None:
        with temp_repo() as repo:
            build_fully_valid_repo(repo)
            failures = check_docs.run_all_checks(repo.root)
            self.assertEqual(failures, [])

    def test_main_returns_zero_on_valid_repo(self) -> None:
        with temp_repo() as repo:
            build_fully_valid_repo(repo)
            with mock.patch.object(check_docs, "repo_root", return_value=repo.root):
                self.assertEqual(check_docs.main(), 0)

    def test_main_returns_one_on_broken_repo(self) -> None:
        with temp_repo() as repo:
            repo.add_resource("rule")  # no doc, no readme link
            repo.set_provider_go("")
            repo.add_tf_file("provider.tf")
            repo.set_tf_readme("nothing mentioned\n")
            repo.set_readme("nothing here\n")
            with mock.patch.object(check_docs, "repo_root", return_value=repo.root):
                self.assertEqual(check_docs.main(), 1)


if __name__ == "__main__":
    unittest.main()
